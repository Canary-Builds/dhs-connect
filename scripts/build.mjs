import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';
const root = new URL('../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const source = await readFile(new URL('src/client.js', root), 'utf8');
await mkdir(new URL('lib/', root), { recursive: true });
const bundle = `// Generated by npm run build. Edit src/client.js.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(pkg.name)},factory:(require)=>{\n${source}\nreturn { inject, apply, CodexSettings };\n}});\n`;
new Script(bundle, { filename: 'lib/client.js' });
await writeFile(new URL('lib/client.js', root), bundle);
console.log(`Built client registration for ${pkg.name}`);
